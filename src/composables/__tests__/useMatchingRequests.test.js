// Regression / integration coverage for the "matching engine silently finds
// nothing" bug fixed on this branch (commit 82c8d44). Three independent breaks
// combined to make searchMatches() never return a match even with perfectly
// compatible mock data:
//   1. useOwnerProfile() was destructured as `ownerProfile` but the composable
//      actually exports `form` -> ownerProfile.value was always undefined.
//   2. The `if (!ownerProfile.value) await fetchProfile()` guard could never
//      fire because `form` defaults to a non-null object -> profile (lat/long)
//      was never actually fetched even after fixing (1).
//   3. listRequests (the Amplify-generated query) only selected `clinicID`,
//      not the nested `clinic` object, so the geo filter's
//      `req.clinic.latitude`/`longitude` read was always undefined -> every
//      Request was dropped by the distance check.
//
// Bug (3) was first "fixed" by hand-editing the generated src/graphql/queries.js
// directly -- but that file is regenerated by `amplify codegen`/`amplify push`
// (see its own header comment), which would have silently wiped the fix on the
// next codegen run and reintroduced the bug with no failing test to catch it,
// since a test only sees whatever query string is checked into git. Moved to a
// new custom query, listOpenRequestsWithClinic in custom-queries.js, following
// this codebase's existing pattern for hand-written queries that need fields
// beyond default codegen output (see getVetWithClinic in the same file) --
// that file is never touched by codegen.
//
// These tests exercise the full chain with a mocked `generateClient().graphql`
// and assert an actual Match comes out the other end, not just "doesn't throw".

const graphqlMock = vi.fn()

vi.mock('aws-amplify/api', () => ({
  generateClient: () => ({ graphql: graphqlMock }),
}))

vi.mock('aws-amplify/auth', () => ({
  getCurrentUser: vi.fn(async () => ({ userId: 'owner-1' })),
}))

